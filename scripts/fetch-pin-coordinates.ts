/* =====================================================================
   Build a sourced PIN-coordinate reference for the bundled Tamil Nadu
   reference PINs, using the public Zippopotam.us (GeoNames) API.

   Run: npx tsx scripts/fetch-pin-coordinates.ts
   Writes lib/data/tamil-nadu-pin-coordinates.ts
   ===================================================================== */

import { writeFileSync } from "node:fs";
import { TN_DISTRICT_PINCODES } from "../lib/data/tamil-nadu-pincodes";

const pins = [...new Set(Object.values(TN_DISTRICT_PINCODES).flat())].sort();
console.log(`reference pins: ${pins.length}`);

type Coord = { lat: number; lng: number; place: string };
const out: Record<string, Coord> = {};
const failed: string[] = [];

async function fetchPin(pin: string): Promise<void> {
  const url = `https://api.zippopotam.us/in/${pin}`;
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const r = await fetch(url, { headers: { accept: "application/json" } });
      if (r.status === 404) { failed.push(pin); return; }
      if (!r.ok) throw new Error(`HTTP ${r.status}`);
      const j = (await r.json()) as { places?: { "place name"?: string; latitude?: string; longitude?: string }[] };
      const p = j.places?.[0];
      if (p?.latitude && p?.longitude) {
        out[pin] = { lat: +p.latitude, lng: +p.longitude, place: p["place name"] ?? "" };
      } else {
        failed.push(pin);
      }
      return;
    } catch {
      await new Promise((r) => setTimeout(r, 400 * (attempt + 1)));
    }
  }
  failed.push(pin);
}

async function run() {
  const CONC = 6;
  for (let i = 0; i < pins.length; i += CONC) {
    await Promise.all(pins.slice(i, i + CONC).map(fetchPin));
    process.stdout.write(`\r${Math.min(i + CONC, pins.length)}/${pins.length} (+${Object.keys(out).length} coords)`);
  }
  console.log("");
  const lines = [
    "/* =====================================================================",
    "   Tamil Nadu PIN → postal-area coordinate reference.",
    "",
    "   Source: Zippopotam.us (https://api.zippopotam.us), a GeoNames-backed",
    "   postal-code lookup. Coordinates identify the PIN's POSTAL area",
    "   (post-office locality) — they are NOT respondent locations and are not",
    "   an exact residence of any survey response.",
    "",
    `   Version: pin-coords-2026-02.1 · ${Object.keys(out).length}/${pins.length} of the bundled reference PINs.`,
    "   Generated by scripts/fetch-pin-coordinates.ts. Do not hand-edit.",
    "   ===================================================================== */",
    "",
    "export const PIN_COORDINATE_REFERENCE = {",
    "  name: \"Tamil Nadu PIN postal-area coordinates\",",
    "  source: \"https://api.zippopotam.us (GeoNames)\",",
    "  version: \"pin-coords-2026-02.1\",",
    "  kind: \"postal-reference\" as const,",
    "  note:",
    "    \"Coordinates identify the PIN's postal area (post-office locality). They are not respondent \" +",
    "    \"locations and are not exact residences of any survey response.\",",
    "} as const;",
    "",
    "export type PinPostalCoord = { lat: number; lng: number; place: string };",
    "",
    "/** PIN → postal-area coordinate (post-office locality). */",
    "export const PIN_COORDINATES: Record<string, PinPostalCoord> = {",
  ];
  for (const pin of Object.keys(out).sort()) {
    const c = out[pin];
    lines.push(`  "${pin}": { lat: ${c.lat}, lng: ${c.lng}, place: ${JSON.stringify(c.place)} },`);
  }
  lines.push("};", "");
  lines.push(`export const PIN_COORDINATE_COVERAGE = { total: ${pins.length}, withCoordinates: ${Object.keys(out).length}, withoutCoordinates: ${pins.length - Object.keys(out).length} } as const;`);
  lines.push("");
  writeFileSync("lib/data/tamil-nadu-pin-coordinates.ts", lines.join("\n"));
  console.log(`wrote lib/data/tamil-nadu-pin-coordinates.ts — coords ${Object.keys(out).length}, failed ${failed.length}`);
  if (failed.length) console.log("failed pins:", failed.slice(0, 40).join(", "));
}

run();
