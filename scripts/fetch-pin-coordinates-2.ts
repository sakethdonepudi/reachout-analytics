/* =====================================================================
   Second-pass PIN-coordinate lookup for the bundled Tamil Nadu reference
   PINs that Zippopotam.us did not cover, using OpenStreetMap Nominatim.

   Validation: a Nominatim hit is only accepted when the returned
   state_district / county matches the PIN's reference district (after alias
   normalisation). Mismatches and misses stay UNRESOLVED (no coordinate).

   Run: npx tsx scripts/fetch-pin-coordinates-2.ts
   Rewrites lib/data/tamil-nadu-pin-coordinates.ts with both sources.
   ===================================================================== */

import { writeFileSync } from "node:fs";
import { TN_DISTRICT_PINCODES } from "../lib/data/tamil-nadu-pincodes";
import { PIN_COORDINATES } from "../lib/data/tamil-nadu-pin-coordinates";
import { canonicalDistrictKey } from "../lib/pin";

const stripDistrict = (s: string) => canonicalDistrictKey(String(s).replace(/\b(districts?|taluk|taluka|revenue division)\b/gi, ""));

// reference district per PIN
const PIN_DISTRICT = new Map<string, string>();
for (const [district, pins] of Object.entries(TN_DISTRICT_PINCODES)) for (const p of pins) if (!PIN_DISTRICT.has(p)) PIN_DISTRICT.set(p, district);

const allPins = [...new Set(Object.values(TN_DISTRICT_PINCODES).flat())].sort();
const existing: Record<string, { lat: number; lng: number; place: string; src: "zippopotam" | "nominatim" }> = {};
for (const [k, v] of Object.entries(PIN_COORDINATES)) existing[k] = { lat: v.lat, lng: v.lng, place: v.place, src: ((v as { src?: "zippopotam" | "nominatim" }).src) ?? "zippopotam" };

const missing = allPins.filter((p) => !existing[p]);
console.log(`total ${allPins.length} · zippopotam ${Object.keys(existing).length} · to look up ${missing.length}`);

type Hit = { lat: number; lng: number; place: string; src: "nominatim"; district: string };
const added: Record<string, Hit> = {};
const rejected: { pin: string; got: string; want: string }[] = [];
const misses: string[] = [];

async function lookup(pin: string): Promise<void> {
  const want = PIN_DISTRICT.get(pin) ?? "";
  const url = `https://nominatim.openstreetmap.org/search?postalcode=${pin}&country=India&format=json&addressdetails=1&limit=1`;
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const r = await fetch(url, { headers: { "User-Agent": "reachout-analytics-pin-audit/1.0 (postal reference build)", accept: "application/json" } });
      if (r.status === 429) { await new Promise((res) => setTimeout(res, 2000 * (attempt + 1))); continue; }
      if (!r.ok) throw new Error(`HTTP ${r.status}`);
      const j = (await r.json()) as { lat?: string; lon?: string; display_name?: string; address?: Record<string, string> }[];
      const hit = j?.[0];
      if (!hit?.lat || !hit?.lon) { misses.push(pin); return; }
      const got = hit.address?.state_district || hit.address?.county || hit.address?.city || "";
      if (stripDistrict(got) && stripDistrict(got) === stripDistrict(want)) {
        added[pin] = { lat: +hit.lat, lng: +hit.lon, place: (hit.display_name ?? "").split(",")[0] || pin, src: "nominatim", district: want };
      } else {
        rejected.push({ pin, got, want });
      }
      return;
    } catch {
      await new Promise((res) => setTimeout(res, 1500 * (attempt + 1)));
    }
  }
  misses.push(pin);
}

async function run() {
  for (let i = 0; i < missing.length; i++) {
    await lookup(missing[i]);
    if (i % 10 === 0) process.stdout.write(`\r${i + 1}/${missing.length} (+${Object.keys(added).length} accepted, ${rejected.length} rejected)`);
    await new Promise((res) => setTimeout(res, 1100)); // Nominatim rate limit
  }
  console.log("");
  const merged: Record<string, { lat: number; lng: number; place: string; src: string }> = { ...existing, ...added };
  const pins = Object.keys(merged).sort();
  const lines = [
    "/* =====================================================================",
    "   Tamil Nadu PIN → postal-area coordinate reference.",
    "",
    "   Sources:",
    "     - Zippopotam.us (https://api.zippopotam.us), GeoNames-backed",
    "     - OpenStreetMap Nominatim (https://nominatim.openstreetmap.org), filtered",
    "       to hits whose district matches the PIN's reference district",
    "",
    "   Coordinates identify the PIN's POSTAL area (post-office locality). They",
    "   are NOT respondent locations and are not exact residences of any survey",
    "   response. Unresolved PINs have no entry here and are shown without a map",
    "   position (the 433-PIN set is a bundled subset, not the full TN directory).",
    "",
    `   Version: pin-coords-2026-02.2 · ${pins.length}/${allPins.length} of the bundled reference PINs.`,
    "   Generated by scripts/fetch-pin-coordinates*.ts. Do not hand-edit.",
    "   ===================================================================== */",
    "",
    "export type PinCoordSource = \"zippopotam\" | \"nominatim\";",
    "",
    "export const PIN_COORDINATE_REFERENCE = {",
    "  name: \"Tamil Nadu PIN postal-area coordinates\",",
    "  source: \"Zippopotam.us (GeoNames) + OpenStreetMap Nominatim\",",
    "  version: \"pin-coords-2026-02.2\",",
    "  kind: \"postal-reference\" as const,",
    "  note:",
    "    \"Coordinates identify the PIN's postal area (post-office locality). They are not respondent \" +",
    "    \"locations and are not exact residences of any survey response. The bundled PIN set is a \" +",
    "    \"subset, not the complete Tamil Nadu postal directory.\",",
    "} as const;",
    "",
    "export type PinPostalCoord = { lat: number; lng: number; place: string; src: PinCoordSource };",
    "",
    "/** PIN → postal-area coordinate (post-office locality). */",
    "export const PIN_COORDINATES: Record<string, PinPostalCoord> = {",
  ];
  for (const pin of pins) { const c = merged[pin]; lines.push(`  "${pin}": { lat: ${c.lat}, lng: ${c.lng}, place: ${JSON.stringify(c.place)}, src: ${JSON.stringify(c.src)} },`); }
  lines.push("};", "");
  lines.push(`export const PIN_COORDINATE_COVERAGE = { total: ${allPins.length}, withCoordinates: ${pins.length}, withoutCoordinates: ${allPins.length - pins.length} } as const;`);
  writeFileSync("lib/data/tamil-nadu-pin-coordinates.ts", lines.join("\n"));
  console.log(`wrote module — total coords ${pins.length}/${allPins.length}; nominatim accepted ${Object.keys(added).length}; rejected ${rejected.length}; miss ${misses.length}`);
  if (rejected.length) console.log("rejected (district mismatch):", rejected.slice(0, 20).map((r) => `${r.pin} got="${r.got}" want="${r.want}"`).join(" | "));
}

run();
